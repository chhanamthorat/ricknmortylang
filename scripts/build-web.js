// Bundles the interpreter + the example programs into one file the
// browser can load: docs/ricknmortylang.js
//
// no webpack, no rollup, just glue. run with: npm run build:web

const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const modules = ["errors", "lexer", "parser", "interpreter"];

let out = "// generated by scripts/build-web.js, don't edit by hand\n";
out += "(function () {\n";
out += "  var defs = {}, cache = {};\n";
out += "  function require(name) {\n";
out += "    name = name.replace('./', '');\n";
out += "    if (!cache[name]) { var module = { exports: {} }; cache[name] = module; defs[name](module, module.exports); }\n";
out += "    return cache[name].exports;\n";
out += "  }\n";

for (const name of modules) {
  const src = fs.readFileSync(path.join(root, "src", name + ".js"), "utf8");
  out += `\n  // ----- src/${name}.js -----\n`;
  out += `  defs[${JSON.stringify(name)}] = function (module, exports) {\n${src}\n  };\n`;
}

// the examples get baked in so the playground dropdown has them
const examplesDir = path.join(root, "examples");
const examples = fs
  .readdirSync(examplesDir)
  .filter((f) => f.endsWith(".schwifty"))
  .sort()
  .map((file) => ({ file, code: fs.readFileSync(path.join(examplesDir, file), "utf8") }));

out += "\n  var interp = require('interpreter');\n";
out += "  window.RickNMortyLang = {\n";
out += "    Interpreter: interp.Interpreter,\n";
out += "    show: interp.show,\n";
out += "    SchwiftyError: require('errors').SchwiftyError,\n";
out += "    keywords: require('lexer').KEYWORDS,\n";
out += `    examples: ${JSON.stringify(examples)}\n`;
out += "  };\n";
out += "})();\n";

fs.mkdirSync(path.join(root, "docs"), { recursive: true });
fs.writeFileSync(path.join(root, "docs", "ricknmortylang.js"), out);
console.log(`built docs/ricknmortylang.js (${examples.length} examples, ${(out.length / 1024).toFixed(1)} KB)`);
